const scalar = async (db, statement) => (await db.query(statement)).rows[0];
const snapshot = async (db) => {
  const result = {};
  for (const table of tables) {
    if ((await scalar(db, `select to_regclass('public.${table}') is not null as present`)).present) {
      result[table] = (await scalar(db, `select count(*)::int as total from public.${table}`)).total;
    }
  }
  return result;
};
const assertInfrastructure = async (db) => {
  assert.equal((await scalar(db, 'select count(*)::int as total from auth.users')).total,2);
  assert.deepEqual(await scalar(db, 'select id::int from storage.objects'),{id:99});
  assert.deepEqual(await scalar(db, 'select id::int from extensions.operator_canary'),{id:88});
  assert.equal((await scalar(db, "select to_regprocedure('public.rls_auto_enable()') is not null as present")).present,true);
  assert.equal((await scalar(db, "select count(*)::int as total from pg_event_trigger where evtname='platform_rls_canary' and evtenabled='O'")).total,1);
};
const expectRefusal = async (change, fragment) => {
  const db = await fixture();
  try {
    await db.exec(change);
    const before = await snapshot(db);
    await assert.rejects(db.exec(sql),error=>error.message.includes(fragment));
    assert.deepEqual(await snapshot(db),before,'A refusal must leave every legacy row intact');
    assert.equal((await scalar(db, "select to_regprocedure('public.init_leave_balance()') is not null as present")).present,true);
    await assertInfrastructure(db);
  } finally { await db.close(); }
};

